"""Pydantic models for policy document ingestion and semantic search (camelCase JSON)."""

from datetime import datetime, timezone
from typing import Literal
from enum import Enum

from pydantic import Field, field_validator

from app.schemas.onboarding import CamelModel


class DocumentStatus(str, Enum):
    PROCESSING = "processing"
    READY = "ready"
    FAILED = "failed"


class DocumentFileType(str, Enum):
    PDF = "pdf"
    DOCX = "docx"
    TXT = "txt"


class PolicyDocument(CamelModel):
    id: str
    filename: str
    file_type: DocumentFileType
    size_bytes: int
    status: DocumentStatus
    page_count: int | None
    chunk_count: int
    error_message: str | None
    uploaded_at: datetime

    @field_validator("uploaded_at")
    @classmethod
    def _assume_utc(cls, value: datetime) -> datetime:
        # SQLite returns CURRENT_TIMESTAMP (UTC) without a timezone; make it explicit so clients convert correctly.
        return value.replace(tzinfo=timezone.utc) if value.tzinfo is None else value


class PolicyChunk(CamelModel):
    id: int
    chunk_index: int
    page_number: int | None
    section: str | None
    text: str


class PolicyDocumentDetail(PolicyDocument):
    chunks: list[PolicyChunk]


class PolicySearchRequest(CamelModel):
    query: str = Field(min_length=2, max_length=500)
    top_k: int = Field(default=5, ge=1, le=20)
    document_id: str | None = None

    @field_validator("query")
    @classmethod
    def _strip_query(cls, value: str) -> str:
        stripped = value.strip()
        if len(stripped) < 2:
            raise ValueError("Query must contain at least 2 non-space characters")
        return stripped


class PolicySearchResult(CamelModel):
    chunk_id: int
    document_id: str
    document_name: str
    chunk_index: int
    page_number: int | None
    section: str | None
    text: str
    score: float = Field(description="Cosine similarity between the query and the chunk (higher is more relevant)")


class PolicySearchResponse(CamelModel):
    query: str
    results: list[PolicySearchResult]
    embedding_model: str
    searched_chunks: int


# ---- Policy Assistant chat ----

MAX_HISTORY_MESSAGES = 12
MAX_HISTORY_MESSAGE_CHARS = 4000


class ChatHistoryMessage(CamelModel):
    role: Literal["user", "assistant"]
    content: str = Field(min_length=1, max_length=MAX_HISTORY_MESSAGE_CHARS)


class PolicyChatRequest(CamelModel):
    question: str = Field(min_length=2, max_length=1000)
    history: list[ChatHistoryMessage] = Field(default_factory=list, max_length=MAX_HISTORY_MESSAGES)
    document_id: str | None = None

    @field_validator("question")
    @classmethod
    def _strip_question(cls, value: str) -> str:
        stripped = value.strip()
        if len(stripped) < 2:
            raise ValueError("Question must contain at least 2 non-space characters")
        return stripped


EvidenceLevel = Literal["strong", "moderate", "weak", "insufficient", "no_documents"]


class PolicyCitation(CamelModel):
    source_id: str = Field(description="Reference used in the answer text, e.g. 'S1'")
    chunk_id: int
    document_id: str
    document_name: str
    page_number: int | None
    section: str | None
    excerpt: str
    score: float


class PolicyConflict(CamelModel):
    """Two retrieved passages from different documents that state different figures for the same thing."""

    source_ids: list[str]
    document_names: list[str]
    values: list[str]
    unit: str
    description: str


class EvidenceSummary(CamelModel):
    level: EvidenceLevel
    top_score: float | None = Field(description="Best retrieval similarity (not a probability of correctness)")
    supporting_passages: int
    explanation: str
    # Added in Phase 3.3 (optional, defaults to empty: backward compatible).
    conflicts: list[PolicyConflict] = Field(default_factory=list)


class EscalationInfo(CamelModel):
    recommended: bool
    reason: str | None = None


class PolicyChatResponse(CamelModel):
    answer: str
    citations: list[PolicyCitation]
    evidence: EvidenceSummary
    escalation: EscalationInfo
    answered_from_documents: bool = Field(description="True when the answer was generated by the LLM from cited passages")
    model: str | None = None


AssistantState = Literal["ready", "not_configured", "provider_unreachable", "no_documents", "indexing", "retrieval_unavailable"]
ProviderConnection = Literal["not_checked", "connected", "not_configured", "auth_failed", "unreachable", "timeout", "model_not_found", "error"]


class ProviderStatus(CamelModel):
    """The AI provider as configured on the server. Never includes the API key or the full URL."""

    configured: bool
    model: str
    host: str | None = Field(default=None, description="Provider host, e.g. 'api.openai.com' or 'localhost:11434'")
    connection: ProviderConnection = "not_checked"
    message: str | None = None
    checked_at: datetime | None = None


class KnowledgeStatus(CamelModel):
    total_documents: int
    ready_documents: int
    processing_documents: int
    failed_documents: int
    indexed_passages: int = Field(description="Vectors in this server's FAISS index")
    expected_passages: int = Field(description="Passages of ready documents in the database")
    retrieval_available: bool
    message: str | None = None


class AssistantStatus(CamelModel):
    # Original fields (kept for compatibility).
    llm_configured: bool
    llm_model: str
    embedding_model: str
    ready_documents: int
    # The first thing preventing answers, or "ready".
    state: AssistantState = "ready"
    provider: ProviderStatus | None = None
    knowledge: KnowledgeStatus | None = None
